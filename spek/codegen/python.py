"""Compile a spec into pytest cases.

This is the whole inversion in one file: nothing here emits implementation
code. Examples become `Case` records, outcome names become the thing the
runtime asserts, and hatches become comments plus a triage table -- visible,
counted, and deliberately not executed.
"""

from __future__ import annotations

import keyword
import os
import re
from pathlib import Path

from ..lint import triage
from ..spec_ast import (
    Bool,
    Literal,
    Named,
    Null,
    Num,
    Spec,
    SpecFile,
    Str,
    Sym,
)

VERSION = "0.1.0"
HEADER_MARK = "generated by spek"


def _ident(text: str) -> str:
    cleaned = re.sub(r"[^0-9A-Za-z_]", "_", text).strip("_") or "spec"
    if cleaned[0].isdigit() or keyword.iskeyword(cleaned):
        cleaned = f"spec_{cleaned}"
    return cleaned


def _py(lit: Literal) -> str:
    """Render a spec literal as the Python expression a test will use."""
    if isinstance(lit, Str):
        return repr(lit.value)
    if isinstance(lit, Num):
        return repr(lit.value)
    if isinstance(lit, Bool):
        return "True" if lit.value else "False"
    if isinstance(lit, Null):
        return "None"
    if isinstance(lit, Sym):
        return f"Ref({lit.name!r})"
    if isinstance(lit, Named):
        return _py(lit.value)
    raise TypeError(f"cannot lower {lit!r}")


def _call_parts(spec: Spec, example) -> tuple[list[str], dict[str, str], dict[str, str]]:
    """Split an example's inputs into args, keyword args and setup bindings."""
    params = spec.signature.params
    args = [_py(lit) for lit in example.positional]
    kwargs: dict[str, str] = {}
    setup: dict[str, str] = {}
    for named in example.named:
        target = kwargs if named.name in params else setup
        target[named.name] = _py(named.value)
    return args, kwargs, setup


def _dict_src(mapping: dict[str, str]) -> str:
    inner = ", ".join(f"{key!r}: {value}" for key, value in mapping.items())
    return "{" + inner + "}"


def _cases_src(spec: Spec, var: str) -> list[str]:
    outcomes = ", ".join(repr(o) for o in spec.signature.outcomes)
    outcomes_src = f"({outcomes},)" if len(spec.signature.outcomes) == 1 else f"({outcomes})"

    lines = [f"{var} = ["]
    for example in spec.examples:
        args, kwargs, setup = _call_parts(spec, example)
        args_src = f"({', '.join(args)},)" if len(args) == 1 else f"({', '.join(args)})"
        fields = [
            f"spec={spec.name!r}",
            f"target={spec.name!r}",
            f"args={args_src}",
        ]
        if kwargs:
            fields.append(f"kwargs={_dict_src(kwargs)}")
        if setup:
            fields.append(f"setup={_dict_src(setup)}")
        fields.append(f"outcome={example.outcome!r}")
        fields.append(f"outcomes={outcomes_src}")
        if example.expect is not None:
            fields.append(f"expect={_py(example.expect)}")
            fields.append("has_expect=True")
        fields.append(f"line={example.span.line}")
        lines.append("    Case(")
        for field in fields:
            lines.append(f"        {field},")
        lines.append("    ),")
    lines.append("]")
    return lines


def _spec_block(spec: Spec) -> list[str]:
    var = f"{_ident(spec.name).upper()}_CASES"
    func = f"test_{_ident(spec.name)}"
    params = ", ".join(spec.signature.params)
    outcomes = " | ".join(spec.signature.outcomes)

    lines = ["", "", f"# {spec.name}({params}) -> {outcomes}"]
    if spec.effects:
        lines.append("#   " + " ".join(f"!{tag}" for tag in spec.effect_tags))
    for note in spec.notes:
        lines.append(f"#   : {note.text}")
    for hatch in spec.hatches:
        lines.append(f"#   ? {hatch.text}    <- not verified; a human must check this")

    if not spec.examples:
        lines.append(f"# no examples: nothing to run for {spec.name}")
        return lines

    lines.extend(_cases_src(spec, var))
    lines.extend(
        [
            "",
            "",
            f'@pytest.mark.parametrize("case", {var}, ids=[c.id for c in {var}])',
            f"def {func}(case: Case) -> None:",
            "    run_case(_IMPL, case)",
        ]
    )
    return lines


def _triage_src(spec_file: SpecFile) -> list[str]:
    lines = ["SPEK_TRIAGE = {"]
    for spec in spec_file:
        hatches = ", ".join(repr(h.text) for h in spec.hatches)
        lines.append(
            f"    {spec.name!r}: "
            f'{{"triage": {triage(spec)!r}, "hatches": [{hatches}], '
            f'"examples": {len(spec.examples)}}},'
        )
    lines.append("}")
    return lines


def generate_tests(
    spec_file: SpecFile,
    impl: str,
    out_path: str | Path,
    impl_is_module: bool = False,
) -> str:
    """Render the pytest module for a parsed spec file.

    `impl` is either a filesystem path to the implementation or, when
    `impl_is_module` is set, an importable dotted module name.
    """
    out_path = Path(out_path)
    source_name = spec_file.path or "<spec>"

    if impl_is_module:
        impl_lines = [f"import {impl} as _IMPL"]
    else:
        relative = _relative_to(Path(impl), out_path.parent)
        impl_lines = [
            "_IMPL = load_module_from_path(",
            f"    Path(__file__).resolve().parent / {relative!r}",
            ")",
        ]

    header = [
        f"# {HEADER_MARK} {VERSION} from {source_name} -- do not edit.",
        f"# Regenerate: spek build {source_name} --impl {impl} --out {out_path.parent}",
        '"""Verification compiled from a spec. Every case below is one example line."""',
        "",
        "from __future__ import annotations",
        "",
        "from pathlib import Path",
        "",
        "import pytest",
        "",
        "from spek.runtime import Case, Ref, load_module_from_path, run_case",
        "",
        *impl_lines,
        "",
    ]

    body: list[str] = []
    for spec in spec_file:
        body.extend(_spec_block(spec))

    tail = ["", "", *_triage_src(spec_file), ""]
    return "\n".join(header + body + tail)


def _relative_to(target: Path, start: Path) -> str:
    """A path from the generated test back to the implementation."""
    try:
        return os.path.relpath(target.resolve(), start.resolve())
    except ValueError:  # different drives on Windows
        return str(target.resolve())


def fixtures_stub(spec_file: SpecFile) -> str:
    """A starting fixtures file naming every symbol the examples referenced.

    Left deliberately unfilled: `known` means whatever this codebase means by
    it, and only the author knows that.
    """
    symbols: dict[str, list[str]] = {}
    setup_names: dict[str, list[str]] = {}
    for spec in spec_file:
        for symbol in spec.symbols:
            symbols.setdefault(symbol, []).append(spec.name)
        for example in spec.examples:
            for named in example.named:
                if named.name not in spec.signature.params:
                    setup_names.setdefault(named.name, []).append(spec.name)

    lines = [
        '"""Fixtures for the symbols used in ' + (spec_file.path or "the spec") + '.',
        "",
        "Each entry binds a bare word from an example to a real value. Wrap a factory",
        "in Fresh(...) when the value is mutable and each example needs its own.",
        '"""',
        "",
        "from spek.runtime import Fresh  # noqa: F401  (used by generated entries)",
        "",
        "FIXTURES = {",
    ]
    if not symbols:
        lines.append("    # every example used literal values; nothing to bind")
    for symbol, users in symbols.items():
        lines.append(f"    # used by: {', '.join(sorted(set(users)))}")
        lines.append(f"    {symbol!r}: NotImplemented,")
    lines.append("}")

    if setup_names:
        lines.extend(
            [
                "",
                "",
                "def setup(spec: str, bindings: dict) -> None:",
                '    """Put the world into the state an example assumes.',
                "",
                f"    Named bindings seen in the spec: {', '.join(sorted(setup_names))}",
                '    """',
                "    raise NotImplementedError(f'setup {spec} with {bindings}')",
            ]
        )
    lines.append("")
    return "\n".join(lines)
